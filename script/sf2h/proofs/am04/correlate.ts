/**
 * AM04 correlation gate for hosted, immutable execution observations.
 *
 * This is NOT a domain adapter, grant issuer, test double, or PASS oracle.
 * A successful structural correlation is never a substitute for externally
 * verifying the GitHub Actions run, product runtime, effective model, real
 * host principal, scanner binary and durable receipts against their sources.
 *
 * In particular, a browser response dropped AFTER the handler returned
 * cannot prove interruption between the domain commit and case reconciliation.
 */
export type Am04GateResult = Readonly<{
  status: "REJECTED" | "CORRELATABLE_NOT_ATTESTED"
  findings: readonly string[]
  run: string | null
  receipt: string | null
}>

type ObjectValue = Record<string, unknown>

function object(value: unknown): ObjectValue | null {
  return value !== null && typeof value === "object" && !Array.isArray(value) ? value as ObjectValue : null
}

function nonempty(value: unknown): value is string {
  return typeof value === "string" && value.trim().length > 0
}

function hex(value: unknown, length: number): value is string {
  return typeof value === "string" && new RegExp("^[a-f0-9]{" + length + "}$").test(value)
}

function integer(value: unknown): value is number {
  return typeof value === "number" && Number.isSafeInteger(value) && value >= 0
}

const sequence = [
  "model-prepared",
  "model-apply-denied",
  "human-choice",
  "human-review",
  "human-apply-authorized",
  "planner-authority-revalidated",
  "planner-domain-committed",
  "response-lost-before-case",
  "new-host-binding",
  "planner-receipt-read",
  "case-reconciled",
  "same-key-retry",
  "different-digest-conflict",
  "procurement-authority-revalidated",
  "procurement-denied",
  "partial-case-observed",
] as const

type Phase = typeof sequence[number]

function stage(events: readonly ObjectValue[], phase: Phase, problems: string[]): ObjectValue | null {
  const matching = events.filter((event) => event.phase === phase)
  if (matching.length !== 1) {
    problems.push("stage-exactly-once:" + phase)
    return null
  }
  return matching[0]!
}

/** Correlates original source receipts, not descriptions generated by an LLM. */
export function correlateAm04(input: unknown): Am04GateResult {
  const problems: string[] = []
  const capture = object(input)
  const run = object(capture?.run)
  const host = object(capture?.host)
  const raw = capture?.events
  const events = Array.isArray(raw) ? raw.map(object) : []
  const runId = nonempty(run?.workflowRunId) ? run.workflowRunId : null
  if (capture?.schema !== "sf2h.am04.hosted-observation.v1") problems.push("schema-missing-or-incompatible")
  if (run?.provider !== "github-actions-hosted" || !runId || !nonempty(run?.jobId) ||
    !integer(run?.attempt) || !hex(run?.candidateSha, 40) || !hex(run?.treeSha, 40) ||
    !hex(run?.sourceSha, 40) || !hex(run?.artifactSha256, 64) ||
    !Array.isArray(run?.selectors) || run.selectors.length === 0 ||
    !run.selectors.every(nonempty)) problems.push("hosted-run-identity-unverifiable")

  const requiredHost = [
    "runtimeImplementation", "nativeSessionId", "providerObjectId", "providerGeneration",
    "installationId", "projectId", "principalRef", "authenticatedRequestRef",
    "accessRevision", "modelRunId", "effectiveModelId", "loadedSkillId",
    "loadedSkillVersion", "loadedSkillDigest", "modelOutputDigest",
    "scannerBinaryPath", "scannerBinaryDigest", "scannerVersion", "scannerInvocationId",
  ] as const
  if (!host || requiredHost.some((field) => !nonempty(host[field])) ||
    host.hostAuthentication !== "Application.authenticate(Request)" ||
    host.modelExecution !== "real-native-model" || host.scannerResult !== "clean" ||
    !hex(host.loadedSkillDigest, 64) || !hex(host.modelOutputDigest, 64) ||
    !hex(host.scannerBinaryDigest, 64) ||
    host.syntheticGrant === true || host.mockModel === true || host.mockScanner === true) {
    problems.push("real-native-model-scanner-authentication-not-established")
  }

  if (!Array.isArray(raw) || events.some((event) => !event)) problems.push("events-not-objects")
  const validEvents = events.filter((event): event is ObjectValue => event !== null)
  const observed = new Map<Phase, ObjectValue | null>()
  for (const name of sequence) observed.set(name, stage(validEvents, name, problems))
  const seenSeq = new Set<number>()
  let previous = -1
  for (const name of sequence) {
    const event = observed.get(name)
    if (!event) continue
    if (!integer(event.seq) || event.seq <= previous || seenSeq.has(event.seq)) problems.push("event-order-or-duplicate:" + name)
    else { previous = event.seq; seenSeq.add(event.seq) }
    if (!hex(event.witnessSha256, 64) || !nonempty(event.runStepId) ||
      event.principalRef !== host?.principalRef || event.installationId !== host?.installationId ||
      event.projectId !== host?.projectId || event.providerGeneration !== host?.providerGeneration) {
      problems.push("event-witness-or-host-binding:" + name)
    }
  }
  if (validEvents.length !== sequence.length) problems.push("unaccounted-or-duplicated-events")

  const at = (name: Phase) => observed.get(name)
  const prepared = at("model-prepared")
  const attemptedModelApply = at("model-apply-denied")
  const choice = at("human-choice")
  const review = at("human-review")
  const authorize = at("human-apply-authorized")
  if (prepared?.actorKind !== "model" || prepared?.effectCount !== 0 ||
    attemptedModelApply?.actorKind !== "model" || attemptedModelApply?.outcome !== "denied" ||
    choice?.actorKind !== "human" || choice?.authorization !== "human-choice-grant" ||
    review?.actorKind !== "human" || review?.authorization !== "source-specific-review" ||
    authorize?.actorKind !== "human" || authorize?.authorization !== "separate-human-apply-grant" ||
    !nonempty(choice?.choiceId) || !nonempty(choice?.caseId) || !nonempty(choice?.caseIncarnation) ||
    !integer(choice?.caseVersion) || choice?.choiceId !== authorize?.choiceId ||
    choice?.caseId !== authorize?.caseId || choice?.caseIncarnation !== authorize?.caseIncarnation ||
    review?.reviewDigest !== authorize?.reviewDigest || !hex(review?.reviewDigest, 64)) {
    problems.push("model-preparation-not-separated-from-human-choice-review-and-apply")
  }

  const plannerAuth = at("planner-authority-revalidated")
  const committed = at("planner-domain-committed")
  const lost = at("response-lost-before-case")
  const binding = at("new-host-binding")
  const receiptRead = at("planner-receipt-read")
  const reconciled = at("case-reconciled")
  const retry = at("same-key-retry")
  const collision = at("different-digest-conflict")
  const procurementAuth = at("procurement-authority-revalidated")
  const procurement = at("procurement-denied")
  const partial = at("partial-case-observed")
  const key = committed?.idempotencyKey
  const digest = committed?.commandDigest
  const receipt = nonempty(committed?.receiptId) ? committed.receiptId : null
  const beforeDomain = committed?.domainVersionBefore
  const afterDomain = committed?.domainVersionAfter
  const beforeEffects = committed?.effectCountBefore
  const afterEffects = committed?.effectCountAfter
  const beforeCase = choice?.caseVersion

  if (plannerAuth?.domain !== "planner" || plannerAuth?.outcome !== "authorized" ||
    plannerAuth?.targetIncarnation !== committed?.targetIncarnation ||
    plannerAuth?.expectedVersion !== beforeDomain ||
    committed?.domain !== "planner" || committed?.outcome !== "applied" ||
    !nonempty(key) || !hex(digest, 64) || !receipt ||
    !integer(beforeDomain) || !integer(afterDomain) || afterDomain !== beforeDomain + 1 ||
    !integer(beforeEffects) || !integer(afterEffects) || afterEffects !== beforeEffects + 1 ||
    !nonempty(committed?.domainTransactionId) || !nonempty(committed?.receiptTransactionId) ||
    committed?.domainTransactionId !== committed?.receiptTransactionId ||
    committed?.caseVersion !== beforeCase || committed?.receiptPersisted !== true) {
    problems.push("domain-mutation-and-receipt-not-atomically-witnessed")
  }

  if (lost?.interruptionPoint !== "between-domain-commit-and-case-reconciliation" ||
    lost?.caseVersion !== beforeCase || lost?.domainVersion !== afterDomain ||
    lost?.receiptId !== receipt || lost?.caseReceiptPresent !== false ||
    lost?.source !== "host-fault-boundary") problems.push("lost-response-not-isolated-before-case-reconciliation")

  if (binding?.bindingKind !== "new-authenticated-request" ||
    binding?.nativeSessionId === host?.nativeSessionId ||
    !nonempty(binding?.nativeSessionId) ||
    binding?.authenticatedRequestRef === host?.authenticatedRequestRef ||
    !nonempty(binding?.authenticatedRequestRef) ||
    binding?.modelRunId !== host?.modelRunId) problems.push("restart-or-fresh-binding-not-witnessed")

  const shouldMatch = [receiptRead, reconciled, retry, collision]
  if (shouldMatch.some((event) => event?.idempotencyKey !== key ||
    event?.targetIncarnation !== committed?.targetIncarnation ||
    event?.receiptId !== receipt)) problems.push("receipt-identity-lost-across-recovery")

  if (receiptRead?.source !== "durable-domain-receipt-store" ||
    receiptRead?.commandDigest !== digest || receiptRead?.persisted !== true ||
    receiptRead?.domainVersion !== afterDomain || receiptRead?.effectCount !== afterEffects ||
    reconciled?.source !== "case-state-CAS" || reconciled?.commandDigest !== digest ||
    reconciled?.caseVersionBefore !== beforeCase || reconciled?.caseVersionAfter !== (integer(beforeCase) ? beforeCase + 1 : -1) ||
    reconciled?.domainVersion !== afterDomain || reconciled?.effectCount !== afterEffects ||
    !nonempty(reconciled?.caseTransactionId) ||
    reconciled?.caseTransactionId === committed?.domainTransactionId ||
    retry?.outcome !== "receipt-replayed" || retry?.commandDigest !== digest ||
    retry?.domainVersion !== afterDomain || retry?.effectCount !== afterEffects ||
    collision?.outcome !== "conflict" || collision?.commandDigest === digest ||
    !hex(collision?.commandDigest, 64) ||
    collision?.domainVersion !== afterDomain || collision?.effectCount !== afterEffects) {
    problems.push("retry-receipt-CAS-or-changed-digest-conflict-not-witnessed")
  }

  if (procurementAuth?.domain !== "procurement" || procurementAuth?.outcome !== "authorized" ||
    !integer(procurementAuth?.expectedVersion) ||
    procurement?.domain !== "procurement" || procurement?.outcome !== "conflict" ||
    procurement?.effectCountBefore !== procurement?.effectCountAfter ||
    procurement?.domainVersionBefore !== procurement?.domainVersionAfter ||
    !nonempty(procurement?.targetIncarnation) ||
    partial?.caseState !== "partially-applied" ||
    !Array.isArray(partial?.changes) ||
    partial.changes.length !== 2 ||
    partial.changes[0] !== "planner:applied" ||
    partial.changes[1] !== "procurement:conflict" ||
    partial?.preservedReceiptId !== receipt ||
    partial?.plannerEffectCount !== afterEffects ||
    partial?.procurementEffectCount !== procurement?.effectCountAfter ||
    partial?.globalTransactionClaim === true) {
    problems.push("per-domain-revalidation-and-partiality-not-witnessed")
  }

  return {
    status: problems.length === 0 ? "CORRELATABLE_NOT_ATTESTED" : "REJECTED",
    findings: problems,
    run: runId,
    receipt,
  }
}
