import { createProgram, readConfigFile, parseJsonConfigFileContent, sys, TypeFlags, SymbolFlags, isTypeAliasDeclaration } from "typescript"
import type { Type } from "typescript"
import path from "node:path"

export type SfOutputSchemaBuild = { contributions: number; operations: number; skillInputs: number; definitions: number }

const directory = import.meta.dir
const config = readConfigFile(path.join(directory, "../../tsconfig.json"), sys.readFile)
const options = parseJsonConfigFileContent(config.config, sys, path.join(directory, "../.."))
const program = createProgram([path.join(directory, "outputs.ts"), path.join(directory, "skill-inputs.ts")], options.options)
const checker = program.getTypeChecker()
const source = program.getSourceFile(path.join(directory, "outputs.ts"))!
const definitions: Record<string, Record<string, unknown>> = {}
const refs = new Map<Type, string>()
const maps = ["SfContributionOutputMap", "SfOperationOutputMap", "SfSkillInputMap"].map((name, index) => {
  const mapSource = index === 2 ? program.getSourceFile(path.join(directory, "skill-inputs.ts"))! : source
  const declaration = mapSource.statements.find((node) => isTypeAliasDeclaration(node) && node.name.text === name)
  if (!declaration) throw new Error(`SF_SCHEMA_MAP_MISSING:${name}`)
  return Object.fromEntries(checker.getPropertiesOfType(checker.getTypeAtLocation(declaration)).map((property) => [property.name, schema(checker.getTypeOfSymbolAtLocation(property, declaration), property.name)]))
})
const content = '// Generated by generate-output-schemas.ts; do not edit by hand.\nconst definitions = ' + JSON.stringify(definitions, null, 2) + ' as const\n\n' +
  maps.map((map, index) => 'export const ' + ["sfContributionOutputSchemas", "sfOperationOutputSchemas", "sfSkillInputSchemas"][index] + ' = {\n' + Object.entries(map).map(([key, value]) => '  ' + JSON.stringify(key) + ': { ...' + JSON.stringify(value) + ', definitions },').join('\n') + '\n} as const\n').join('\n')
const output = path.join(directory, "output-schemas.ts")
if (process.argv.includes("--check")) {
  if (!(await Bun.file(output).exists()) || await Bun.file(output).text() !== content) throw new Error("SF_OUTPUT_SCHEMAS_STALE")
} else await Bun.write(output, content)
const receipt: SfOutputSchemaBuild = { contributions: Object.keys(maps[0]!).length, operations: Object.keys(maps[1]!).length, skillInputs: Object.keys(maps[2]!).length, definitions: Object.keys(definitions).length }
process.stdout.write(`SF schemas: ${receipt.contributions} contributions, ${receipt.operations} operations, ${receipt.skillInputs} skill inputs; ${receipt.definitions} closed definitions\n`)

function schema(type: Type, location = "output"): Record<string, unknown> {
  if (type.flags & (TypeFlags.Never | TypeFlags.Undefined | TypeFlags.Void)) return { not: {} }
  if (type.flags & (TypeFlags.Any | TypeFlags.Unknown)) throw new Error(`SF_SCHEMA_UNCLOSED:${location}:${checker.typeToString(type)}`)
  if (type.isStringLiteral()) return { const: type.value }
  if (type.isNumberLiteral()) return { const: type.value }
  if (type.flags & TypeFlags.BooleanLiteral) return { const: checker.typeToString(type) === "true" }
  if (type.flags & TypeFlags.String) return { type: "string" }
  if (type.flags & TypeFlags.Number) return { type: "number" }
  if (type.flags & TypeFlags.Boolean) return { type: "boolean" }
  if (type.flags & TypeFlags.Null) return { type: "null" }
  if (type.isUnion()) {
    const members = type.types.filter((member) => !(member.flags & (TypeFlags.Undefined | TypeFlags.Void | TypeFlags.Never)))
    if (members.length === 1) return schema(members[0]!, location)
    if (!members.length) throw new Error("SF_SCHEMA_EMPTY_UNION")
    const existing = refs.get(type)
    if (existing) return { $ref: `#/definitions/${existing}` }
    const name = reserve(type)
    definitions[name] = { anyOf: members.map((member) => schema(member, location)) }
    return { $ref: `#/definitions/${name}` }
  }
  if (checker.isArrayLikeType(type)) {
    const item = type.getNumberIndexType()
    if (!item) throw new Error("SF_SCHEMA_ARRAY_ITEM_MISSING")
    return { type: "array", items: schema(item, location + "[]") }
  }
  if (!(type.flags & (TypeFlags.Object | TypeFlags.Intersection))) throw new Error(`SF_SCHEMA_UNSUPPORTED:${checker.typeToString(type)}`)
  const existing = refs.get(type)
  if (existing) return { $ref: `#/definitions/${existing}` }
  const name = reserve(type)
  if (type.getStringIndexType()) throw new Error(`SF_SCHEMA_OPEN_RECORD:${location}:${name}`)
  const properties = checker.getPropertiesOfType(type)
  definitions[name] = {
    type: "object", additionalProperties: false, ...(type.aliasSymbol?.name === "Period" ? { "x-sf-period": true } : {}),
    properties: Object.fromEntries(properties.map((property) => [property.name, schema(checker.getTypeOfSymbolAtLocation(property, property.valueDeclaration ?? source), location + "." + property.name)])),
    required: properties.filter((property) => !(property.flags & SymbolFlags.Optional)).map((property) => property.name),
  }
  return { $ref: `#/definitions/${name}` }
}

function reserve(type: Type) {
  const base = (type.aliasSymbol?.name ?? type.symbol?.name ?? "Shape").replace(/[^A-Za-z0-9_]/g, "")
  const name = `${base}_${refs.size + 1}`
  refs.set(type, name)
  definitions[name] = {}
  return name
}
