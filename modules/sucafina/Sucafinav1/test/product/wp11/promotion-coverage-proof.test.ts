// Regression for WP10 PR32 @35b9fd4f532abeb1058f00281d4ad8885ca9966f,
// ASTRA-WP10-PROMOTION-PROOF-01. The real C08 baseline/classification and Planner
// produce coverage and money. This fixture supplies private human admissions and
// the consumer's exact-result proof protocol; it is not an installed/native witness.
for (const order of [[0, 1], [1, 0]] as const) test(`source-only promotions establish current coverage proofs in source order ${order.join("-")}`, async () => {
  const fixture = await coverageFixture()
  try {
    const official = await fixture.official()
    for (const index of order) {
      const before = await fixture.readState()
      const current = before.cases[caseRef.id]!
      const source = fixture.refs[index]!
      const baseline = await fixture.baseline.resolveForecastCoverage(source.refId, fixture.readContext)
      const observation = await fixture.planner.simulateScenario({ baseRef: source.refId, operations: [], assumptions: [] }, fixture.readContext)
      if (baseline.status !== "ok" || observation.status !== "ok") throw new Error("Canonical source observation unavailable")
      // This equality is the formerly skipped branch. For v1 its source-first order
      // also differs from the basis-first order generated by canonical reassessment.
      expect(observation.value.costCoverage).toEqual(baseline.value.assessment)
      expect(baseline.value.assessment.evaluatedSourceRefs[0]).toEqual(source)
      if (index === 1) expect(baseline.value.assessment.evaluatedSourceRefs).not.toEqual(fixture.basis.sourceRefs)
      const request = await fixture.request(index, [])
      const context = await fixture.admit("decisions.promote-alternative", request, `promote-${index}`)
      const entered = fixture.controls.entries
      const promoted = await fixture.mutations.addAlternative(request, context)
      expect(promoted.status).toBe("ok")
      if (promoted.status !== "ok") throw new Error(promoted.reason)
      expect(fixture.controls.entries).toBe(entered + 1)
      const after = await fixture.readState()
      const alternative = after.cases[caseRef.id]!.alternatives.at(-1)!
      expect(after.cases[caseRef.id]!.version).toBe(current.version + 1)
      expect(alternative.result.costCoverage.evaluatedSourceRefs).toEqual(fixture.basis.sourceRefs)
      expect(alternative.result).toMatchObject({ knownSubtotal: index === 0 ? 1200 : 2400, total: null, comparisonStatus: "conditioned", restrictions: [] })
      expect(alternative.result.components).toEqual(observation.value.components)
      expect(alternative.result.sourceRefs).toEqual(observation.value.sourceRefs)
      expect(fixture.controls.committedDigests.at(-1)).toBe(digestSfValue(alternative.result))
      expect(await fixture.mutations.addAlternative(request, context)).toEqual(promoted)
      expect(fixture.controls.entries).toBe(entered + 1)
      expect(await fixture.readState()).toEqual(after)
    }
    const request = await fixture.request(1, [{ kind: "replace", targetRef: "line:1", amount: 42, currency: "USD", period: { start: "2027-01-01", end: "2027-01-31" } }])
    const context = await fixture.admit("decisions.promote-alternative", request, "promote-changed")
    const entered = fixture.controls.entries
    const promoted = await fixture.mutations.addAlternative(request, context)
    expect(promoted.status).toBe("ok")
    if (promoted.status !== "ok") throw new Error(promoted.reason)
    const decision = (await fixture.readState()).cases[caseRef.id]!
    expect(fixture.controls.entries).toBe(entered + 1)
    expect(decision.alternatives.at(-1)!.result).toMatchObject({ knownSubtotal: 2242, total: null, comparisonStatus: "conditioned", restrictions: ["preview-not-applied"] })
    expect(decision.alternatives.at(-1)!.result.components.find((component) => component.id === "line:1")?.evidenceState).toBe("hypothetical")
    expect(decision.choices).toEqual([])
    expect(decision.preparedChanges).toEqual([])
    expect(decision.receipts).toEqual([])
    expect(await fixture.official()).toEqual(official)
  } finally { await fixture.close() }
}, 60_000)

for (const fault of ["missing-proof", "revoke", "source-change", "case-change"] as const) test(`source-only promotion refuses ${fault} between coverage observation and commit`, async () => {
  const fixture = await coverageFixture()
  try {
    const before = await fixture.readState()
    const official = await fixture.official()
    const request = await fixture.request(1, [])
    const context = await fixture.admit("decisions.promote-alternative", request, `reject-${fault}`)
    fixture.controls.fault = fault
    const rejected = await fixture.mutations.addAlternative(request, context)
    expect(rejected.status).not.toBe("ok")
    expect("value" in rejected).toBe(false)
    expect(fixture.controls.entries).toBe(1)
    if (fault === "missing-proof") {
      expect(rejected).toEqual({ status: "conflict", reason: "case-changed" })
      expect(fixture.controls.fences).toBe(1)
    }
    fixture.access.allowed = true
    const after = await fixture.readState()
    expect(after.decisionResults).toEqual(before.decisionResults)
    expect(after.cases[caseRef.id]!.alternatives).toEqual([])
    expect(after.cases[caseRef.id]!.choices).toEqual([])
    expect(after.cases[caseRef.id]!.preparedChanges).toEqual([])
    expect(after.cases[caseRef.id]!.receipts).toEqual([])
    expect(Object.values(after.transactions).filter((transaction) => transaction.commandDigest === digestSfValue(request))).toEqual([])
    if (fault === "case-change") {
      expect(after.cases[caseRef.id]).toEqual({ ...before.cases[caseRef.id]!, version: 2, objective: "Concurrent authorized case edit" })
      expect(Object.keys(after.transactions).length).toBe(Object.keys(before.transactions).length + 1)
    } else expect(after).toEqual(before)
    if (fault === "source-change") {
      const changed = await fixture.official()
      const version = rows(changed.versions).find((value) => value.id === "v1")
      expect(rows(version?.lines)[0]?.f).toEqual([7, ...Array(11).fill(200)])
      expect(changed.audit.length).toBe(official.audit.length + 1)
    } else expect(await fixture.official()).toEqual(official)
  } finally { await fixture.close() }
}, 60_000)

async function coverageFixture() {
  const initial = plannerSnapshot()
  initial.data.versions = [100, 200].map((amount, index) => ({ id: `v${index}`, name: `Plan ${index}`, year: 2027, closed: 0,
    lines: [{ id: "line", sec: "opex", el: "licenses", cur: "USD", b: Array(12).fill(amount), a: Array(12).fill(null), f: Array(12).fill(amount) }], fx: [], hc: { positions: [], rates: [], hrAF: {} }, projects: [], lists: {},
  }))
  const fixture = await plannerFixture(initial)
  // C08 uses Dashboard through the canonical scoped persistence driver.
  await fixture.persistence.initializeSources("dashboard")
  const intents = new WeakMap<Request, { action: SfHumanAction; digest: string; operation: string }>()
  const contexts: TrustedUiContext[] = []
  const actions: SfHumanAction[] = ["decisions.portfolio.read", "decisions.coverage", "decisions.promote-alternative"]
  const authorize = async (request: Request) => fixture.access.allowed && intents.has(request) && request.headers.get("authorization") === actor.id
    ? { installationId: "i", projectId: "p", principalRef: actor.id, accessRevision: "1", policyVersion: "1" } : undefined
  const ui = createSfUiAuthority({ authorize, commandIdentity: async (request, operation, digest) => { const intent = intents.get(request); return intent && operation === `sf-human:${intent.action}` && digest === intent.digest ? intent.operation : undefined }, privateCommands: actions.map((action) => `sf-human:${action}`), createId: randomUUID, now: () => Date.parse(plannerAt) })
  const human = createSfHumanAuthority({ origin, ui })
  const admit = async (action: SfHumanAction, payload: unknown, operation: string) => {
    const request = new Request(origin, { method: "POST", headers: { authorization: actor.id, origin, "content-type": "application/json" }, body: JSON.stringify(payload) })
    intents.set(request, { action, digest: digestSfValue(payload), operation })
    const admitted = await human.admit(request, action, payload)
    if (admitted.status !== "ok") throw new Error(admitted.reason)
    contexts.push(admitted.value)
    return admitted.value
  }
  const host: DomainPortHost = { ...fixture.host, requestFor: (context) => context.kind === "ui" ? ui.requestFor(context) : undefined, revalidate: (context) => context.kind === "ui" ? ui.revalidate(context) : Promise.resolve(false) }
  const readContext = await admit("decisions.portfolio.read", { caseRef }, "read")
  const readRequest = host.requestFor(readContext)
  if (!readRequest) throw new Error("Read authority unavailable")
  const writes = new WeakSet<object>()
  const state = createSfProductState({ persistence: fixture.persistence, authorize, createId: randomUUID, proposalCoverageWrites: writes, resolveTarget: async (_request, _snapshot, _namespace, target) => target === caseRef.id ? { incarnation: caseRef.incarnation } : undefined })
  const ports: { baseline?: ReturnType<typeof createDecisionBaselineCoverage> } = {}
  const product = createPlannerProduct({ host, scopedSources: fixture.persistence, coverageFor: (reference, context) => ports.baseline ? ports.baseline.resolveForecastCoverage(reference, context) : Promise.resolve({ status: "unavailable", reason: "baseline-coverage-unavailable" }) })
  const refs: RecordEvidence[] = []
  for (const id of ["v0", "v1"]) {
    const issued = await product.issueSource(id, readContext)
    if (issued.status !== "ok") throw new Error(issued.reason)
    refs.push(issued.value.evidence)
  }
  const basis: CostCoverageBasis = { id: "current-source-proof", version: 1, decisionType: "renewal-transition-v1", categoryIds: [...RENEWAL_TRANSITION_CATEGORIES], additionalCategoryIds: [], sourceRefs: refs }
  const seed: DecisionCase = { ...caseRef, state: "investigating", objective: "Review two current Planner sources", horizon: plannerPeriod, currency: "USD", criteria: [], participants: [actor.id], sourceRefs: refs, alternatives: [], costCoverageBases: [], assumptions: [], questions: [], choices: [], preparedChanges: [], receipts: [], ledger: [] }
  const seeded = await state.transaction(readRequest, { namespace: "cases", expectedStorageVersion: 0, targetRef: caseRef.id, targetIncarnation: caseRef.incarnation, idempotencyKey: "seed", commandDigest: digestSfValue(seed) }, async (value) => { value.cases[caseRef.id] = seed; return { commit: true, value: true } })
  if (seeded.status !== "ok") throw new Error("Case setup unavailable")
  const readState = async () => { const value = await state.read(readRequest, "cases", (value) => value); if (value.status !== "ok") throw new Error("Private case state unavailable"); return value.value }
  const authorizeCase = async (value: DecisionCase, context: TrustedDomainContext) => value.id === caseRef.id && value.incarnation === caseRef.incarnation && value.participants.includes(context.binding.principalRef) && await host.revalidate(context)
  const resolveEvidence = async (requested: readonly BusinessEvidenceRef[], context: TrustedDomainContext): Promise<readonly BusinessEvidenceResolution[]> => Promise.all(requested.map(async (ref): Promise<BusinessEvidenceResolution> => {
    const current = ref.kind === "record" ? await product.sources.resolveForecastSource(ref.refId, context) : undefined
    return { ref, state: current?.status === "ok" && digestSfValue(current.value.evidence) === digestSfValue(ref) ? "fresh" : "revoked", accessRevision: context.binding.accessRevision, checkedAt: plannerAt }
  }))
  const snapshotMatches = (snapshot: Snapshot, requested: readonly BusinessEvidenceRef[]) => requested.every((ref) => {
    if (ref.kind !== "record" || ref.target.surface !== "planner") return false
    const identity = Object.values(snapshot.sfSources?.scopes ?? {}).filter((value) => value.alive && value.scope.principalRef === actor.id && value.incarnation === ref.target.incarnation && value.version === ref.target.version)
    const projection = projectPlannerSource(snapshot, actor, ref.target.recordId)
    return identity.length === 1 && !!projection && digestSfValue({ versionId: ref.target.recordId, projection }) === ref.target.projectionDigest
  })
  const baseline = createDecisionBaselineCoverage({ state, host, resolveCase: async () => { const value = (await readState()).cases[caseRef.id]!; return { status: "ok", value: { id: value.id, incarnation: value.incarnation, version: value.version } } }, authorizeCase,
    authorizeCoverage: (request, context) => human.authorize(context, "decisions.coverage", request),
    projectForecast: async (reference, _case, context) => { const projected = await product.planner.compareForecast({ baseRef: reference, candidateRef: reference, period: plannerPeriod, currency: "USD" }, context); return projected.status === "ok" ? { status: "ok", value: projected.value.candidate } : projected },
    resolveEvidence, supports: () => false, verifySnapshot: (snapshot, _request, record) => snapshotMatches(snapshot, record.assessment.evaluatedSourceRefs), operationIdentity: (context) => context.kind === "ui" ? ui.operationIdentity(context) : undefined, proposalCoverageWrites: writes, now: () => plannerAt,
  })
  ports.baseline = baseline
  const classifications: CoverageClassification[] = []
  for (const source of refs) {
    const projection = await product.planner.compareForecast({ baseRef: source.refId, candidateRef: source.refId, period: plannerPeriod, currency: "USD" }, readContext)
    if (projection.status !== "ok") throw new Error(projection.reason)
    const entries: CostCoverageEntry[] = RENEWAL_TRANSITION_CATEGORIES.map((categoryId) => categoryId === "service" ? { categoryId, status: "included", componentRefs: projection.value.candidate.components.map((component) => component.id), evidenceRefs: [source], scopeNote: "The human classifies the current service components; other categories remain unresolved." } : { categoryId, status: "pending", reason: "human-classification-required" })
    const request = { caseRef, source, basis, entries, expectedVersion: 0 }
    const context = await admit("decisions.coverage", request, `coverage-${source.target.recordId}`)
    const registered = await baseline.register(request, context)
    if (registered.status !== "ok") throw new Error(registered.reason)
    const classification = await baseline.readClassification(source.refId, readContext)
    if (classification.status !== "ok") throw new Error(classification.reason)
    classifications.push(classification.value)
  }
  const supports = (entry: Exclude<CostCoverageEntry, { status: "pending" }>, evidence: readonly BusinessEvidenceResolution[]) => classifications.some((classification) => supportsCoverageClassification(classification, entry, evidence))
  const controls = { fault: "none" as Fault, entries: 0, fences: 0, committedDigests: [] as string[] }
  const proofs = new WeakMap<TrustedDomainContext, { resultDigest: string; basisDigest: string; sourceRefs: readonly BusinessEvidenceRef[] }>()
  const unavailable = async () => ({ status: "unavailable" as const, reason: "outside-promotion-proof" })
  const mutations = createDecisionMutations({ state, host, planner: product.planner, sources: product.sources, authorizeCase,
    authorizeMutation: (operation, payload, context) => operation === "add-alternative" ? human.authorize(context, "decisions.promote-alternative", payload) : Promise.resolve(false),
    verifyMutation: (_snapshot, operation, payload, context) => operation === "add-alternative" && context.kind === "ui" && ui.matchesIntent(context, "sf-human:decisions.promote-alternative", digestSfValue(payload)),
    operationIdentity: (context) => context.kind === "ui" ? ui.operationIdentity(context) : undefined, confirmChoice: async () => false, confirmAnswer: async () => false, resolveQuestion: unavailable, resolveAnswer: unavailable, resolveChoiceValues: unavailable, prepareDomainCommands: unavailable,
    coverageEvidence: {
      entries: async (scenario, assessment, context) => {
        controls.entries++
        const source = scenario.sourceRefs.find((ref) => ref.kind === "record" && ref.target.recordType === "planner-version")
        if (!source) return { status: "unavailable", reason: "source-proof-unavailable" }
        const classified = await baseline.readClassification(source.refId, context)
        const current = await baseline.resolveForecastCoverage(source.refId, context)
        if (classified.status !== "ok" || current.status !== "ok" || digestSfValue(current.value.assessment) !== digestSfValue(assessment)) return { status: "unavailable", reason: "classification-proof-unavailable" }
        const result = await reassessScenarioCoverage({ scenario, basis: current.value.basis, baseline: assessment, entries: assessment.entries, resolveEvidence: (requested) => resolveEvidence(requested, context), supports })
        if (!result || !await host.revalidate(context)) return { status: "unavailable", reason: "result-proof-unavailable" }
        if (controls.fault !== "missing-proof") proofs.set(context, { resultDigest: digestSfValue(result), basisDigest: digestSfValue(current.value.basis), sourceRefs: result.costCoverage.evaluatedSourceRefs })
        if (controls.fault === "revoke") fixture.access.allowed = false
        if (controls.fault === "source-change") await fixture.persistence.transaction("planner", async (snapshot) => {
          const changed = domain.execute(snapshot, actor, { page: "OPEX", action: "save", id: "line", version: 0, values: { versionId: "v1", f0: 7 } }, { at: plannerAt, id: randomUUID, directory: [] })
          if (!changed.ok) throw new Error("Concurrent domain edit unavailable")
          return { commit: true, value: changed }
        })
        if (controls.fault === "case-change") {
          const before = await state.read(readRequest, "cases", (value) => value.cases[caseRef.id])
          if (before.status !== "ok" || !before.value) throw new Error("Concurrent case unavailable")
          const changed = await state.transaction(readRequest, { namespace: "cases", expectedStorageVersion: before.storageVersion, targetRef: caseRef.id, targetIncarnation: caseRef.incarnation, idempotencyKey: "concurrent-case-edit", commandDigest: digestSfValue({ version: before.value.version, objective: "Concurrent authorized case edit" }) }, async (value) => { value.cases[caseRef.id] = { ...before.value!, version: before.value!.version + 1, objective: "Concurrent authorized case edit" }; return { commit: true, value: true } })
          if (changed.status !== "ok") throw new Error("Concurrent case edit unavailable")
        }
        return { status: "ok", value: assessment.entries }
      }, resolve: resolveEvidence, supports,
      verifySnapshot: (snapshot, result, inventory, context) => {
        controls.fences++
        const proof = proofs.get(context)
        const valid = !!proof && proof.resultDigest === digestSfValue(result) && proof.basisDigest === digestSfValue(inventory) && snapshotMatches(snapshot, proof.sourceRefs)
        if (valid) controls.committedDigests.push(digestSfValue(result))
        return valid
      },
    }, createId: randomUUID, now: () => plannerAt,
  })
  const request = async (index: number, operations: readonly ScenarioOperation[]) => {
    const current = (await readState()).cases[caseRef.id]!
    const coverage = await baseline.resolveForecastCoverage(refs[index]!.refId, readContext)
    if (coverage.status !== "ok") throw new Error(coverage.reason)
    return { caseRef: { id: current.id, incarnation: current.incarnation, version: current.version }, title: `Review ${index}`, scenario: { baseRef: refs[index]!.refId, operations, assumptions: [] }, coverageRef: coverage.value.coverageRef }
  }
  const official = async () => { const snapshot = await fixture.readSnapshot(); return structuredClone({ versions: snapshot.data.versions, officials: snapshot.data.officials, audit: snapshot.audit, revisions: snapshot.versions }) }
  return { access: fixture.access, admit, baseline, basis, controls, mutations, official, planner: product.planner, readContext, readState, refs, request, close: async () => { contexts.forEach(human.finish); await fixture.close() } }
}
