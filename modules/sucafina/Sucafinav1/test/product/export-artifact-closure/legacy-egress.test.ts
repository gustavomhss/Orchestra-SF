import { expect, test } from "bun:test"
import { chmod, mkdtemp, realpath, rm } from "node:fs/promises"
import { tmpdir } from "node:os"
import { join } from "node:path"
import JSZip from "jszip"
import { SaxesParser } from "saxes"
import { createApplication } from "../../../runtime/application.ts"
import type { Persistence } from "../../../runtime/contract.ts"
import { openLocalStore } from "../../../runtime/local-store.ts"
import { emptyMap, resolve } from "../../../src/identity.ts"
import { recordExportEvidence } from "./evidence.ts"

test("EA66-LEGACY-EGRESS revocation after the authenticated SQLite read must suppress generated bytes", async () => {
  const directory = await mkdtemp(join(await realpath(tmpdir()), "sf66-legacy-egress-"))
  await chmod(directory, 0o700)
  const store = await openLocalStore(directory)
  const marker = "EA66-SYNTHETIC-AUTHORIZED-NOTE"
  const session = { active: true, authenticatedReads: 0 }
  const scheduling = { revoke: false, revocations: 0 }
  try {
    await store.transaction("dashboard", async (snapshot) => {
      snapshot.data.roleMap = emptyMap().map((row) => ({ ...row, entra: row.surface === "dashboard" && row.role === "admin" ? "egress-admin-group" : null, version: 1, by: "synthetic-fixture" }))
      snapshot.data.hotTopics = [{ id: "egress-source", action: marker, status: "open", priority: "normal" }]
      snapshot.versions["hotTopics:egress-source"] = { version: 1, by: "synthetic-fixture" }
      return { commit: true, value: undefined }
    })
    const before = await store.transaction("dashboard", async (snapshot) => ({ commit: false, value: structuredClone(snapshot) }))
    // Scheduling-only wrapper: the real SQLite callback and returned material are untouched.
    // Revocation occurs after the authorization/read transaction has actually completed.
    const persistence: Persistence = { ...store, transaction: async (surface, work, options) => {
      const result = await store.transaction(surface, work, options)
      if (scheduling.revoke && surface === "dashboard" && result !== null && typeof result === "object" && "snapshot" in result && "actor" in result) {
        scheduling.revoke = false
        scheduling.revocations += 1
        session.active = false
      }
      return result
    } }
    const application = createApplication("/sucafina", {
      persistence,
      authenticate: async (request, context) => {
        if (!session.active || request.headers.get("x-sf66-session") !== "synthetic-egress-session" || !context) return null
        session.authenticatedReads += 1
        return resolve("synthetic-egress-owner", [...context.roleMap], (group) => group === "egress-admin-group")
      },
      environment: async () => ({ at: "2026-11-14T12:00:00Z", id: () => "synthetic-egress-id", directory: [] }),
      domains: { dashboard: [], planner: [], procurement: [] },
      maxJsonBytes: 1024,
    })
    const request = () => new Request("https://example.test/sucafina/dashboard?download=docx&year=2026&title=Egress%20report&topic=Hot%20Topics%20%26%20Actions", { headers: { "x-sf66-session": "synthetic-egress-session" } })
    const control = await application(request())
    if (!control || control.status !== 200) throw new Error(`Authorized DOCX control unavailable: ${control?.status}`)
    const controlBytes = new Uint8Array(await control.arrayBuffer())
    expect(await containsMarker(controlBytes, marker)).toBe(true)
    expect(session.authenticatedReads).toBeGreaterThan(0)
    await recordExportEvidence({ caseId: "legacy-egress-control", name: "Egress_report.docx", mediaType: control.headers.get("content-type") ?? "", bytes: controlBytes,
      observations: { syntheticCorpus: true, authorizedControl: true, sqlite: true, currentSession: session.active } })

    scheduling.revoke = true
    const response = await application(request())
    if (!response) throw new Error("Legacy export route unavailable")
    const bytes = new Uint8Array(await response.arrayBuffer())
    const leaked = response.status === 200 && await containsMarker(bytes, marker)
    if (response.status === 200) await recordExportEvidence({ caseId: "legacy-egress-revoked", name: "Egress_report.docx", mediaType: response.headers.get("content-type") ?? "", bytes,
      observations: { syntheticCorpus: true, sqlite: true, revokedAfterAuthorizedRead: scheduling.revocations === 1, status: response.status, generatedContentLeaked: leaked, criterionVerdict: "FAIL" } })
    const afterRevocation = await application(request())
    expect(afterRevocation?.status).toBe(401)
    expect(scheduling.revocations).toBe(1)
    expect(session.active).toBe(false)
    expect(await store.transaction("dashboard", async (snapshot) => ({ commit: false, value: structuredClone(snapshot) }))).toEqual(before)
    console.info("SF66_LEGACY_EGRESS", JSON.stringify({ status: response.status, sessionRevoked: !session.active, revocations: scheduling.revocations, generatedContentLeaked: leaked, nextRequestStatus: afterRevocation?.status }))
    expect(response.status).toBe(403)
    expect(leaked).toBe(false)
  } finally {
    await store.dispose()
    await rm(directory, { recursive: true, force: true })
  }
}, 30000)

async function containsMarker(bytes: Uint8Array, marker: string) {
  const archive = await JSZip.loadAsync(bytes)
  const document = archive.file("word/document.xml")
  if (!document) throw new Error("Generated bytes are not a DOCX main document")
  const parts: string[] = []
  const reader = new SaxesParser({ xmlns: false })
  reader.on("text", (value) => parts.push(value))
  reader.write(await document.async("string")).close()
  return parts.join("\n").includes(marker)
}
