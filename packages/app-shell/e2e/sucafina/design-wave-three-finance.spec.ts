async function verifyNativeScroller(page: Page) {
  const scroller = page.locator('[data-sf-frame="page"] .mx-page')
  await expect.poll(() => scroller.evaluate((element) => element.clientHeight)).toBeGreaterThan(0)
  await expect.poll(() => scroller.evaluate((element) => element.scrollHeight - element.clientHeight)).toBeGreaterThan(0)
  await scroller.evaluate((element) => element.scrollTo({ top: element.scrollHeight, behavior: "instant" }))
  await expect.poll(() => scroller.evaluate((element) => element.scrollTop)).toBeGreaterThan(0)
  await scrollPageTop(page)
}

